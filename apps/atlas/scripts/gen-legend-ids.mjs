// Generates apps/atlas/src/seo/legendIds.gen.ts from content/legends/*.md (read only).
import { readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const legendsDir = resolve(here, '../../../content/legends');
const out = resolve(here, '../src/seo/legendIds.gen.ts');

let files = [];
try {
  files = readdirSync(legendsDir).filter((f) => f.endsWith('.md'));
} catch (err) {
  console.error(`gen-legend-ids: cannot read ${legendsDir}: ${err.message}`);
  process.exit(1);
}
if (files.length === 0) {
  console.error(`gen-legend-ids: no legend files in ${legendsDir}`);
  process.exit(1);
}
const ids = files.map((f) => f.slice(0, -3)).sort();
const body = `// GENERATED by scripts/gen-legend-ids.mjs from content/legends/*.md. Do not edit by hand.
export const LEGEND_IDS = [
${ids.map((id) => `  '${id}',`).join('\n')}
] as const;
`;
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, body);
console.log(`gen-legend-ids: wrote ${ids.length} ids to ${out}`);
